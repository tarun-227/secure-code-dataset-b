"""Task pools for the row planner, with tags that say which row specifications each task fits.

Each task is (description, tags). tools/build_plan.py picks a task only when its tags fit the row's pattern,
fix type, input source and file operation, so a row never asks for something contradictory.

CWE-89   kind: value (a text value in a condition), number, identifier (a table/column/sort name), list (several ids),
               multi (several optional filters), stored (a value saved earlier in the database is used in a new query)
CWE-78   kind: host (host name or address), file (a file name passed to a tool), action (one of a few operations),
               text (free text passed to a tool), format (a strictly formatted value: number, date, version, port),
               report (a fixed command whose output is filtered by the input)
CWE-22   op:   read, write, delete, rename, serve, extract
         name: flat (one file name), nested (a relative path with folders), choice (one of a few known files)
         ext:  True when the task is about one kind of file (images, logs, ...), so an extension check is natural
CWE-338  value: token, otp, password, session, salt, key   (main)
         pattern: the hard-negative pattern a non-security task fits (nonsec)
no_code tasks need no tags.
"""


